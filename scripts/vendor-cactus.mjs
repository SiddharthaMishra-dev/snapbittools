#!/usr/bin/env node

/**
 * Vendors the Cactus engine WebAssembly build used by the Image to Text (Mirage) tool.
 *
 * Downloads the pinned release from huggingface.co/Cactus-Compute/cactus, verifies each file
 * against the release manifest checksums, and writes it to apps/web/src/vendor/cactus/.
 *
 * Usage: bun scripts/vendor-cactus.mjs
 *
 * The upstream loader is a classic script that defines `createCactus`. It is stored as
 * `cactus.mjs` with one appended line (`export default createCactus;`) so Vite can import it
 * from a module worker. The rest of the file is unchanged.
 *
 * To upgrade: update ENGINE_VERSION, ENGINE_REVISION, and FILES (sizes and sha256 come from
 * releases/<version>/manifest.json), and update MIRAGE_ENGINE in apps/web/src/lib/mirage.ts.
 */

import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ENGINE_VERSION = "4.1.2";
const ENGINE_REVISION = "569a10bb4f0e87331abcf874903c0e5139d38aae";
const FILES = {
  "wasm/cactus.js": "707341e44776ab0eb8dfc8f6a579ed5ac41e2ffc6419a18012f61619a6dfc70c",
  "wasm/cactus.wasm": "5a87c5f97ef3175a078ced8c643675aeda9d78d88c2fc327e368330a6151bb2b",
  LICENSE: null,
};

const base = `https://huggingface.co/Cactus-Compute/cactus/resolve/${ENGINE_REVISION}/releases/${ENGINE_VERSION}`;
const outDir = join(dirname(fileURLToPath(import.meta.url)), "../apps/web/src/vendor/cactus");

async function download(path, sha256) {
  const response = await fetch(`${base}/${path}`);
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  const actual = createHash("sha256").update(bytes).digest("hex");
  if (sha256 && actual !== sha256) throw new Error(`${path}: sha256 ${actual} does not match ${sha256}`);
  return bytes;
}

await mkdir(outDir, { recursive: true });

const loader = await download("wasm/cactus.js", FILES["wasm/cactus.js"]);
await writeFile(join(outDir, "cactus.mjs"), Buffer.concat([loader, Buffer.from("\nexport default createCactus;\n")]));
await writeFile(join(outDir, "cactus.wasm"), await download("wasm/cactus.wasm", FILES["wasm/cactus.wasm"]));
await writeFile(join(outDir, "LICENSE"), await download("LICENSE", FILES.LICENSE));
await writeFile(
  join(outDir, "README.md"),
  `# Cactus engine (vendored)

WebAssembly build of the [Cactus](https://github.com/cactus-compute/cactus) engine, release
${ENGINE_VERSION} at revision \`${ENGINE_REVISION}\` of
[Cactus-Compute/cactus](https://huggingface.co/Cactus-Compute/cactus). Apache-2.0, see \`LICENSE\`.

Generated by \`scripts/vendor-cactus.mjs\`. Do not edit by hand. \`cactus.mjs\` is upstream
\`wasm/cactus.js\` with \`export default createCactus;\` appended.
`,
);

console.log(`Vendored Cactus engine ${ENGINE_VERSION} into ${outDir}`);
